/** 상황과 직무에 맞는 대사 하나(보여 주기 전용이라 Math.random을 쓴다) */
export function pickLine(mood: Mood, role: Role): string {
  const pool = LINES[mood].filter((l) => l[0] === '*' || l[0] === role);
  return pool[Math.floor(Math.random() * pool.length)][1];
}
